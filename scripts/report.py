"""Build results/summary.md and results/scores.csv from transcripts and latency logs (no keys, no GPU)."""
import csv
import glob
import pathlib
import statistics as st
from collections import defaultdict

from bntts.score import best_cer

ROOT = pathlib.Path(__file__).resolve().parents[1]
CATS = ["news", "conversational", "numbers", "conjuncts", "banglish"]


def load_rows():
    return {r["id"]: r for r in csv.DictReader(open(ROOT / "data/testset.tsv", encoding="utf-8"), delimiter="\t")}


def score(judge_csv, rows):
    """Per clip: CER on the raw-input clip, scored after normalising both sides (spoken=True) and
    with no normalisation (spoken=False). Code-mixed rows accept either script."""
    out = []
    for r in csv.DictReader(open(judge_csv, encoding="utf-8")):
        rid, variant = r["clip"].split(".")
        ref = rows[rid]
        refs = [ref["spoken"], ref["text"]]
        out.append(dict(system=r["system"], id=rid, variant=variant, category=ref["category"],
                        cer=best_cer(refs, r["hyp"], spoken=True), cer_strict=best_cer(refs, r["hyp"], spoken=False),
                        off=int(off_script(r["hyp"]) and ref["category"] != "banglish"
                                or any("\u0a00" <= c <= "\u0dff" or ("\u0900" <= c <= "\u097f" and c not in "\u0964\u0965") for c in r["hyp"])),
                        hyp=r["hyp"]))
    return out


def latency():
    lat = defaultdict(list)
    for f in glob.glob(str(ROOT / "results/latency_*.csv")):
        for r in csv.DictReader(open(f, encoding="utf-8")):
            if r["status"] == "ok":
                lat[r["system"]].append((float(r["ttfb_s"]), float(r["total_s"]), float(r["audio_s"])))
    return lat


def off_script(hyp):
    """True when the judge answered mostly outside Bengali script and Latin (e.g. Gujarati, or romanised Bangla
    for a fully Bangla sentence). Counted separately: it is a judge failure as much as a TTS one."""
    letters = [c for c in hyp if c.isalpha()]
    if not letters:
        return True
    bn = sum("\u0980" <= c <= "\u09ff" for c in letters)
    return bn / len(letters) < 0.5


def pct(xs, q):
    xs = sorted(xs)
    return xs[min(len(xs) - 1, int(round(q * (len(xs) - 1))))]


def main():
    rows = load_rows()
    lines = ["# Results (generated by scripts/report.py; do not edit by hand)", ""]
    for judge in sorted(glob.glob(str(ROOT / "results/asr_*.csv"))):
        name = pathlib.Path(judge).stem[4:]
        sc = score(judge, rows)
        with open(ROOT / f"results/scores_{name}.csv", "w", newline="", encoding="utf-8") as fh:
            w = csv.DictWriter(fh, list(sc[0].keys())); w.writeheader(); w.writerows(sc)
        by = defaultdict(list)
        for s in sc:
            by[s["system"]].append(s)
        lines += [f"## Judge: {name}", "",
                  "| system | n | CER % (normalised) | CER % (strict) | error-free | " + " | ".join(CATS) + " | numbers, bnnorm input | judge off-script | CER % excl. off-script |",
                  "|---|---|---|---|---|" + "---|" * len(CATS) + "---|---|---|"]
        order = sorted(by, key=lambda k: st.mean(x["cer"] for x in by[k] if x["variant"] == "raw"))
        for sysname in order:
            raw = [x for x in by[sysname] if x["variant"] == "raw"]
            norm = [x for x in by[sysname] if x["variant"] == "norm" and x["category"] == "numbers"]
            cat = [st.mean(x["cer"] for x in raw if x["category"] == c) * 100 if any(x["category"] == c for x in raw) else float("nan") for c in CATS]
            nn = f"{st.mean(x['cer'] for x in norm) * 100:.1f}" if norm else "n/a"
            lines.append(f"| {sysname} | {len(raw)} | {st.mean(x['cer'] for x in raw) * 100:.1f} | "
                         f"{st.mean(x['cer_strict'] for x in raw) * 100:.1f} | {sum(x['cer'] == 0 for x in raw)}/{len(raw)} | "
                         + " | ".join(f"{c:.1f}" for c in cat) + f" | {nn} | {sum(x['off'] for x in raw)} | "
                         + (f"{st.mean(x['cer'] for x in raw if not x['off']) * 100:.1f}" if any(not x['off'] for x in raw) else "n/a") + " |")
        lines.append("")
    lat = latency()
    if lat:
        lines += ["## Latency (API systems, same client, per sentence)", "",
                  "| system | n | TTFB median s | total median s | total p90 s | audio s total |", "|---|---|---|---|---|---|"]
        for k, v in sorted(lat.items()):
            lines.append(f"| {k} | {len(v)} | {st.median(x[0] for x in v):.2f} | {st.median(x[1] for x in v):.2f} | "
                         f"{pct([x[1] for x in v], 0.9):.2f} | {sum(x[2] for x in v):.0f} |")
    (ROOT / "results/summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
